import { createHash } from "node:crypto";
import { mkdir, readFile, writeFile } from "node:fs/promises";
import path from "node:path";
import sharp from "sharp";

const root = process.cwd();
const collection = path.join(root, "docs/licenses/third-party/smithsonian-open-access");
const config = JSON.parse(await readFile(path.join(collection, "assets.json"), "utf8"));
const publicDir = path.join(root, "public");
const manifest = [];
const entries = [];
const sha256 = (bytes) => createHash("sha256").update(bytes).digest("hex");

if (config.schemaVersion !== 1 || config.sourceLicense !== "CC0 1.0 Universal") throw new Error("Unsupported Smithsonian source/license manifest");
for (const item of config.assetRecords) {
  const record = JSON.parse(await readFile(path.join(collection, item.recordFile), "utf8"));
  const content = record.content;
  const descriptive = content?.descriptiveNonRepeating;
  const media = descriptive?.online_media?.media ?? [];
  const chosenMedia = media.find((candidate) => candidate.usage?.access === "CC0" && candidate.resources?.some((resource) => resource.url === item.sourceMediaUrl));
  const sourceRecordId = item.recordFile.split("/").at(-1).replace(/\.json$/, "").replace(/^chndm-/, "");
  const recordId = descriptive?.record_ID?.replace(/^chndm_/, "");
  const metadataRights = descriptive?.metadata_usage?.access;
  const objectRights = content?.freetext?.objectRights?.some((right) => right.content === "CC0");
  if (!chosenMedia || metadataRights !== "CC0" || recordId !== sourceRecordId || objectRights !== true) {
    throw new Error(`Rights/provenance mismatch for ${item.id}: record=${recordId}, metadata=${metadataRights}, objectRights=${objectRights}`);
  }

  const originalPath = path.join(collection, item.originalFile);
  const original = await readFile(originalPath);
  const image = sharp(original, { failOn: "error" });
  const input = await image.metadata();
  let normalized = image;
  if (item.crop) normalized = normalized.extract(item.crop);
  const outputPath = path.join(publicDir, item.outputFile);
  await mkdir(path.dirname(outputPath), { recursive: true });
  const output = await normalized.rotate().resize({ width: 2400, height: 2400, fit: "inside", withoutEnlargement: true }).webp({ quality: 90, effort: 5 }).toBuffer();
  await writeFile(outputPath, output);
  const dimensions = await sharp(output).metadata();
  const source = `Smithsonian Open Access — Cooper Hewitt, Smithsonian Design Museum${chosenMedia ? ` (record ${descriptive.record_ID})` : ""}`;
  const sourceUrl = descriptive.record_link;
  const licenseUrl = config.licenseUrl;
  const title = descriptive.title?.content ?? record.title;
  const creatorCredits = content?.freetext?.name?.map((entry) => `${entry.content} (${entry.label.toLowerCase()})`) ?? [];
  const creatorNames = content?.freetext?.name?.map((entry) => entry.content) ?? [];
  const date = content?.freetext?.date?.map((entry) => entry.content).join("; ") ?? null;
  const place = content?.freetext?.place?.map((entry) => entry.content).join("; ") ?? null;
  const sourceRecord = {
    id: item.id,
    title,
    recordId: descriptive.record_ID,
    sourceRecordUrl: sourceUrl,
    sourceMediaUrl: item.sourceMediaUrl,
    metadataAccess: metadataRights,
    objectAccess: chosenMedia.usage.access,
    recordRightsNotice: objectRights ? "CC0" : null,
    license: config.sourceLicense,
    licenseUrl,
    attributionRequired: false,
    recommendedCredit: item.useCredit,
    creatorCredits,
    date,
    place,
    originalFile: item.originalFile,
    originalSha256: sha256(original),
    sourceDimensions: { width: input.width, height: input.height },
    crop: item.crop,
    derivativeFile: item.outputFile,
    derivativeSha256: sha256(output),
    derivativeDimensions: { width: dimensions.width, height: dimensions.height },
  };
  manifest.push(sourceRecord);
  entries.push({
    id: item.id,
    name: item.name,
    kind: item.kind,
    category: item.category,
    tags: item.tags,
    license: config.sourceLicense,
    source: item.sourceName ?? (creatorNames.length ? `${source}; ${creatorNames.join(", ")}` : source),
    sourceUrl,
    evidenceUrl: config.rightsEvidence,
    licenseId: "CC0-1.0",
    licenseUrl,
    attributionRequired: false,
    attributionText: item.useCredit,
    commercialUse: true,
    modificationAllowed: true,
    redistributionAllowed: true,
    imageUrl: `/${item.outputFile}`,
    width: dimensions.width,
    height: dimensions.height,
  });
}

await writeFile(path.join(collection, "SOURCE-MANIFEST.json"), `${JSON.stringify({ schemaVersion: 1, generatedAt: "reproducible from bundled originals and records", assets: manifest }, null, 2)}\n`);
const generatedTs = `/** Generated by scripts/ingest-smithsonian-open-access.mjs from bundled CC0 records and originals. */\nimport type { StudioAsset } from "./asset-library";\n\nexport const SMITHSONIAN_STUDIO_ASSETS: readonly StudioAsset[] = ${JSON.stringify(entries, null, 2)};\n`;
await writeFile(path.join(root, "lib/studio/smithsonian-assets.ts"), generatedTs);
console.log(`Verified and generated ${entries.length} Smithsonian CC0 design assets.`);
